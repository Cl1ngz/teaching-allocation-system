import { readonly } from "vue";

/** The base error type. All errors thrown from apiFetch will be one of these. */
export interface BaseError<Code extends string = string> {
    code: Code;
    detail: string;
    timestamp: Date;
}

/** Special error type wrapping exceptions that can be thrown by fetch(). */
export class FetchError extends Error implements BaseError<"FETCH_FAILED"> {
    code: "FETCH_FAILED";
    detail: string;
    cause: Error;
    timestamp: Date;

    constructor(error: Error) {
        super(error.message);
        this.code = "FETCH_FAILED";
        this.detail = error.message;
        this.cause = error;
        this.timestamp = new Date();
    }
}

/** Special error type wrapping exceptions that can be thrown by Response.json() */
export class ResponseSyntaxError extends Error implements BaseError<"RESPONSE_SYNTAX_ERROR"> {
    code: "RESPONSE_SYNTAX_ERROR";
    detail: string;
    cause: SyntaxError;
    timestamp: Date;

    constructor(error: SyntaxError) {
        super(error.message);
        this.code = "RESPONSE_SYNTAX_ERROR";
        this.detail = error.message;
        this.cause = error;
        this.timestamp = new Date();
    }
}

/** The JSON representation of an API error. */
export interface ApiErrorData {
    status: number;
    code: string;
    title: string;
    detail: string;
    instance: string;
    // ISO 8601
    timestamp: string;
    errorId: string;
}

function isApiErrorData(data: unknown): data is ApiErrorData {
    if (data === null || typeof data !== "object") {
        return false;
    }

    const value = data as Record<string, unknown>;
    return (
        typeof value.status === "number" &&
        typeof value.code === "string" &&
        typeof value.title === "string" &&
        typeof value.detail === "string" &&
        typeof value.instance === "string" &&
        typeof value.timestamp === "string" &&
        typeof value.errorId === "string"
    );
}

/**
 * The class for all errors generated by the API itself (i.e. HTTP errors).
 */
export class ApiError<Code extends string> extends Error implements BaseError<Code> {
    name = "ApiError";

    status!: number;
    title!: string;
    detail!: string;
    instance!: string;
    code!: Code;

    timestamp: Date;
    errorId!: string;

    constructor(data: unknown) {
        if (!isApiErrorData(data)) {
            throw new ResponseSyntaxError(new TypeError("API error has invalid shape"));
        }
        super(`${data.title}: ${data.detail}`);
        Object.assign(this, data);
        this.timestamp = new Date(data.timestamp);
    }
}

/**
 * A helper type to define an endpoint's possible thrown errors.
 * Pass in a union of the endpoint's error types.
 */
export type EndpointErrorType<E extends ApiError<string>> = E | FetchError | ResponseSyntaxError;

// below, any non-endpoint-specific errors

export type MalformedRequestError = ApiError<"MALFORMED_REQUEST">;
export type UnauthenticatedError = ApiError<"UNAUTHENTICATED">;
export type AccessDeniedError = ApiError<"ACCESS_DENIED">;
export type NotFoundError = ApiError<"NOT_FOUND">;
export type MethodNotAllowedError = ApiError<"METHOD_NOT_ALLOWED">;
export type ConflictError = ApiError<"CONFLICT">;
export type ServiceUnavailableError = ApiError<"SERVICE_UNAVAILABLE">;
export type InternalError = ApiError<"INTERNAL_ERROR">;
export interface ValidationFieldError {
    field: string;
    code: string;
    message: string;
}
export type ValidationError = ApiError<"VALIDATION_ERROR"> & { errors: ValidationFieldError[] };

// A mechanism to translate errors into user-facing text messages.
type NarrowErrorUnion<Errors extends BaseError<string>, Code extends string> = Errors & {
    code: Code;
} & {};
export type ErrorDictionary<Errors extends BaseError<string> = BaseError<string>> = {
    [C in Errors["code"]]: string | ((error: NarrowErrorUnion<Errors, C>) => string);
};

export const ErrorDictionary = {
    default: readonly({
        VALIDATION_ERROR: "Niepoprawne parametry zapytania",
        MALFORMED_REQUEST: "Błąd składni zapytania",
        UNAUTHENTICATED: "Wymagane jest zalogowanie",
        ACCESS_DENIED: "Brak uprawnień do wykonania tej operacji",
        NOT_FOUND: "Nie znaleziono zasobu",
        METHOD_NOT_ALLOWED: "Niedozwolona metoda zapytania",
        CONFLICT: "Konflikt stanu serwera",
        SERVICE_UNAVAILABLE: "Serwis niedostępny",
        INTERNAL_ERROR: "Błąd serwera",
        FETCH_FAILED: "Brak połączenia z serwerem",
        RESPONSE_SYNTAX_ERROR: "Niepoprawna odpowiedź serwera",
    }) satisfies ErrorDictionary<
        | MalformedRequestError
        | UnauthenticatedError
        | AccessDeniedError
        | NotFoundError
        | ValidationError
        | MethodNotAllowedError
        | ConflictError
        | ServiceUnavailableError
        | InternalError
        | FetchError
        | ResponseSyntaxError
    >,

    /** Use an error dictionary to translate an error object into a message. */
    translate<Error extends BaseError<string>>(
        error: Error,
        dictionary: ErrorDictionary<Error>,
    ): string | null {
        if (error.code in dictionary) {
            const result = dictionary[error.code as Error["code"]];
            if (typeof result === "string") {
                return result;
            } else {
                return result(error);
            }
        } else {
            return null;
        }
    },

    /** Combine two error dictionaries, so that A will be asked first, and B second. */
    chain<A extends BaseError<string>, B extends BaseError<string>>(
        a: ErrorDictionary<A>,
        b: ErrorDictionary<B>,
    ): ErrorDictionary<A & B> {
        return readonly(Object.assign(Object.create(null), b, a));
    },
};
